"""Thin subprocess wrapper around AFNI command-line tools, plus a CPU budget for running them."""

import contextvars
import functools
import os
import shlex
import subprocess
from concurrent.futures import ThreadPoolExecutor
from contextlib import contextmanager
from pathlib import Path

from .exceptions import ToolExecutionError

# Threads each AFNI process may use (exported as OMP_NUM_THREADS). None leaves the
# environment untouched. Context-local, so concurrent workers can hold different budgets.
_thread_budget: contextvars.ContextVar[int | None] = contextvars.ContextVar("afni_thread_budget", default=None)


@contextmanager
def thread_budget(n_threads):
    """Cap OpenMP threads for AFNI commands run inside this block.

    Without a cap, OpenMP-enabled AFNI programs size themselves to every core
    the host reports, which in a CPU-limited container means heavy throttling.
    """
    token = _thread_budget.set(max(1, int(n_threads)))
    try:
        yield
    finally:
        _thread_budget.reset(token)


def uses_num_cores(run):
    """Decorator for pipeline ``run(config, ...)``: apply ``config.num_cores`` as the thread budget."""
    @functools.wraps(run)
    def wrapper(config, *args, **kwargs):
        with thread_budget(config.num_cores):
            return run(config, *args, **kwargs)
    return wrapper


def parallel_map(fn, items):
    """Apply ``fn`` to each item concurrently, splitting the current thread budget.

    Workers = min(len(items), budget); each worker runs with budget // workers
    threads. Results keep input order. With no budget set, or a budget of 1,
    items run sequentially. The first worker exception is re-raised.
    """
    items = list(items)
    budget = _thread_budget.get() or 1
    workers = min(len(items), budget)
    if workers <= 1:
        return [fn(item) for item in items]

    per_worker = budget // workers

    def call(item):
        with thread_budget(per_worker):
            return fn(item)

    with ThreadPoolExecutor(max_workers=workers) as pool:
        return list(pool.map(call, items))


def clean_deconvolve_err(out_dir=None):
    """Remove 3dDeconvolve.err file if it exists (always generated by AFNI).

    Checks both the current working directory and out_dir (if provided).
    """
    for directory in filter(None, [".", out_dir]):
        (Path(directory) / "3dDeconvolve.err").unlink(missing_ok=True)


def run_afni_command(command, capture_output=False, description="", logger=None):
    """
    Run an AFNI command via subprocess with standardized error handling.

    Parameters
    ----------
    command : list of str or os.PathLike
        The command and arguments.
    capture_output : bool
        If True, capture and return stdout.
    description : str
        Human-readable description for logging.
    logger : logging.Logger, optional

    Returns
    -------
    subprocess.CompletedProcess or str
        If capture_output is True, returns stdout as a string.
        Otherwise returns the CompletedProcess object.

    Raises
    ------
    ToolExecutionError
        If the command exits with non-zero status. Message includes the
        command, description, and stderr.
    """
    command = [os.fspath(arg) for arg in command]
    cmd_str = shlex.join(command)
    if logger:
        logger.debug("Running: %s", cmd_str)

    try:
        env = os.environ.copy()
        env['AFNI_COMPRESSOR'] = 'GZIP'
        n_threads = _thread_budget.get()
        if n_threads is not None:
            env['OMP_NUM_THREADS'] = str(n_threads)
        result = subprocess.run(
            command,
            capture_output=True,
            text=True,
            check=True,
            env=env,
        )
        if capture_output:
            return result.stdout
        return result
    except subprocess.CalledProcessError as e:
        desc = f" ({description})" if description else ""
        msg = f"AFNI command failed{desc}: {cmd_str}"
        if e.stderr:
            msg += f"\n  stderr: {e.stderr.strip()}"
        if logger:
            logger.error("AFNI command failed%s: %s", desc, cmd_str)
            if e.stderr:
                logger.error("stderr: %s", e.stderr.strip())
        raise ToolExecutionError(msg) from e


_3DINFO_QUERIES = {"space": "-space", "orient": "-orient", "spacing": "-ad3", "dmax": "-dmax"}

# (resolved path, mtime_ns, size) -> complete property dict
_3DINFO_CACHE: dict[tuple, dict] = {}


def _normalize_3dinfo_value(key, out):
    # -ad3 prints three voxel sizes; normalize separators so values compare equal
    # regardless of whether they came from a combined or a single-flag call.
    return "\t".join(out.split()) if key == "spacing" else out.strip()


def _query_3dinfo(nifti_path, logger):
    # One combined call: 3dinfo prints the requested values on one line in flag
    # order -> space, orient, dx, dy, dz, dmax.
    try:
        out = run_afni_command(
            ["3dinfo", *_3DINFO_QUERIES.values(), nifti_path],
            capture_output=True,
            description=f"3dinfo {nifti_path}",
            logger=logger,
        )
        fields = out.split()
        if len(fields) == 6:
            return {"space": fields[0], "orient": fields[1],
                    "spacing": "\t".join(fields[2:5]), "dmax": fields[5]}
        if logger:
            logger.debug("Unexpected combined 3dinfo output for %s (%r); querying per flag.", nifti_path, out)
    except ToolExecutionError:
        if logger:
            logger.debug("Combined 3dinfo call failed for %s; querying per flag.", nifti_path)

    # Fallback: one call per flag, so a single failing query yields None for that key only
    props = {}
    for key, flag in _3DINFO_QUERIES.items():
        try:
            out = run_afni_command(
                ["3dinfo", flag, nifti_path],
                capture_output=True,
                description=f"3dinfo {flag} {nifti_path}",
                logger=logger,
            )
            props[key] = _normalize_3dinfo_value(key, out)
        except ToolExecutionError:
            if logger:
                logger.error("Could not retrieve %s from %s with 3dinfo.", key, nifti_path)
            props[key] = None
    return props


def get_3dinfo_properties(nifti_path, logger=None):
    """
    Get key properties from a NIfTI file via 3dinfo.

    Complete results are cached per (resolved path, mtime, size), so repeated
    template/scan validations within a process do not re-run 3dinfo.

    Returns
    -------
    dict with keys: 'space', 'orient', 'spacing', 'dmax'
    """
    try:
        path = Path(nifti_path).resolve()
        st = path.stat()
        key = (str(path), st.st_mtime_ns, st.st_size)
    except OSError:
        key = None

    if key in _3DINFO_CACHE:
        return dict(_3DINFO_CACHE[key])

    props = _query_3dinfo(nifti_path, logger)
    if key is not None and all(v is not None for v in props.values()):
        _3DINFO_CACHE[key] = dict(props)
    return props
